#!/usr/bin/env python
"""Benchmark inference (v3): rank the mAbs v3 test sheet with a seed ensemble.

Input:  data/benchmark_mAbs_v3.csv  (group, seq_id, antigen_name, antigen,
        VH, VL — generated by data_pipeline/parse_v3_xlsx.py from the v3
        benchmark xlsx, which is not tracked and must be placed manually)
Output: predictions/mAbs_ranking.csv (+ scores/ranks per seed)

Encoder conventions are identical to training (extraction/):
  AntiBERTy: [CLS] chain [SEP], char vocab, specials stripped, heavy->light concat
  ESM-2 650M: <cls>..<eos> stripped; >1000 aa windowed (1000/500, mean overlap)

Ensemble: per-group mean of the seeds' ranks (Borda) -> final Rank 1..N
(1 = highest predicted affinity). Group sizes are read from the data
(no hard-coded 20-per-group assumption). Per-row antigens: every row is
scored with its own antigen embedding.

Chain-aware checkpoints (T3.5 arm) are detected from the checkpoint config;
chain_ids are derived from len(VH) — the extraction keeps heavy->light order.
Struct-arm checkpoints (struct_ab_dim/struct_ag_dim > 0) are likewise detected
from the checkpoint config; pooled ProstT5 embeddings are extracted with the
same disk-caching convention under extraction/cache_benchmark/struct_{ab,ag}/.

Run from the repo root:
  .venv/bin/python training/infer_benchmark.py \
      [--test-csv data/benchmark_mAbs_v3.csv] \
      [--ckpt-dirs deleak_final_s0 deleak_final_s1 deleak_final_s2] \
      [--out predictions/mAbs_ranking.csv]
"""

import argparse
import hashlib
import json
import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "extraction"))
sys.path.insert(0, str(ROOT / "training"))

from extract_antiberty import AntiBERTyEncoder  # noqa: E402
from extract_antigens import esm_hidden_windowed  # noqa: E402
from extract_embeddings import pad_batch  # noqa: E402
from transformers import AutoModel, AutoTokenizer  # noqa: E402

from data import collate_antibodies  # noqa: E402
from model import AffinityRanker  # noqa: E402

log = logging.getLogger("infer")

DEFAULT_TEST_CSV = ROOT / "data" / "benchmark_mAbs_v3.csv"
DEFAULT_CKPT_DIRS = [f"deleak_final_s{s}" for s in (0, 1, 2)]
CACHE_DIR = ROOT / "extraction" / "cache_benchmark"
ESM_DIR = ROOT / "model_data" / "esm2-650m"
DEFAULT_OUT = ROOT / "predictions" / "mAbs_ranking.csv"


def clean_ab(seq: str) -> str:
    return seq.strip().rstrip("X*")


def clean_ag(seq: str) -> str:
    return seq.strip().rstrip("*")


# ---------------------------------------------------------------------------
# Extraction (disk-cached under extraction/cache_benchmark/)
# ---------------------------------------------------------------------------

@torch.no_grad()
def extract_antibody(enc, vh, vl, cache_dir):
    """h_ab fp16 [L,512] = concat(heavy, light); cached by sha1(vh|vl)."""
    key = hashlib.sha1((vh + "|" + vl).encode()).hexdigest()[:16]
    path = cache_dir / "ab" / key[:2] / f"{key}.npz"
    if path.exists():
        with np.load(path) as z:
            return z["h_ab"].astype(np.float32)
    chains = [enc.encode_ids(vh)] + ([enc.encode_ids(vl)] if vl else [])
    ids, mask = pad_batch(chains)
    h = enc.model(ids.to(enc.device), attention_mask=mask.to(enc.device)).last_hidden_state
    parts = [h[k, 1: len(c) - 1].to(torch.float16).cpu().numpy()
             for k, c in enumerate(chains)]
    h_ab = np.concatenate(parts, axis=0)
    assert h_ab.shape[0] == len(vh) + len(vl)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(path, h_ab=h_ab)
    return h_ab.astype(np.float32)


@torch.no_grad()
def extract_antigen(tok, model, seq, cache_dir):
    """h_ag fp16 [L,1280]; windowed for >1000 aa; cached by sha1(seq)."""
    key = hashlib.sha1(seq.encode()).hexdigest()[:16]
    path = cache_dir / "ag" / key[:2] / f"{key}.npz"
    if path.exists():
        with np.load(path) as z:
            return z["h_ag"].astype(np.float32)
    h_ag = esm_hidden_windowed(tok, model, seq)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(path, h_ag=h_ag)
    return h_ag.astype(np.float32)


@torch.no_grad()
def extract_struct_ab(enc, vh, vl, cache_dir):
    """Pooled ProstT5 [1024] fp32; cached by sha1(vh|vl)."""
    key = hashlib.sha1((vh + "|" + vl).encode()).hexdigest()[:16]
    path = cache_dir / "struct_ab" / key[:2] / f"{key}.npy"
    if path.exists():
        return np.load(path).astype(np.float32)
    chains = [vh] + ([vl] if vl else [])
    h = np.concatenate(enc.hidden_chains(chains), axis=0)
    vec = h.mean(axis=0).astype(np.float32)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.save(path, vec)
    return vec


@torch.no_grad()
def extract_struct_ag(enc, seq, cache_dir):
    """Pooled ProstT5 [1024] fp32; cached by sha1(seq)."""
    key = hashlib.sha1(seq.encode()).hexdigest()[:16]
    path = cache_dir / "struct_ag" / key[:2] / f"{key}.npy"
    if path.exists():
        return np.load(path).astype(np.float32)
    h = enc.hidden_chains([seq])[0]
    vec = h.mean(axis=0).astype(np.float32)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.save(path, vec)
    return vec


# ---------------------------------------------------------------------------
# Scoring
# ---------------------------------------------------------------------------

@torch.no_grad()
def score_group(model, h_abs, h_ags, device, chain_lens=None,
                s_abs=None, s_ags=None):
    """One batch of rows with per-row antigens -> scores [n]."""
    struct_kw = {}
    if getattr(model, "struct_ab_dim", 0) > 0:
        struct_kw["s_ab"] = torch.from_numpy(np.stack(s_abs)).to(device)
    if getattr(model, "struct_ag_dim", 0) > 0:
        struct_kw["s_ag"] = torch.from_numpy(np.stack(s_ags)).to(device)
    if model.chain_aware:
        h_ab, ab_mask, chain_ids = collate_antibodies(
            [torch.from_numpy(h) for h in h_abs], chain_lens)
        h_ag, ag_mask = collate_antibodies_ag(h_ags)
        sc = model(h_ab.to(device), ab_mask.to(device),
                   h_ag.to(device), ag_mask.to(device),
                   chain_ids=chain_ids.to(device), **struct_kw)
    else:
        h_ab, ab_mask = collate_antibodies([torch.from_numpy(h) for h in h_abs])
        h_ag, ag_mask = collate_antibodies_ag(h_ags)
        sc = model(h_ab.to(device), ab_mask.to(device),
                   h_ag.to(device), ag_mask.to(device), **struct_kw)
    return sc.float().cpu().numpy()


def collate_antibodies_ag(h_list):
    """Pad [L_i,1280] antigen tensors -> (h_ag [B,Lmax,1280], mask [B,Lmax])."""
    b, lmax = len(h_list), max(h.shape[0] for h in h_list)
    h_ag = torch.zeros(b, lmax, h_list[0].shape[1])
    mask = torch.zeros(b, lmax, dtype=torch.bool)
    for i, h in enumerate(h_list):
        h_ag[i, : h.shape[0]] = torch.from_numpy(h)
        mask[i, : h.shape[0]] = True
    return h_ag, mask


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--test-csv", type=Path, default=DEFAULT_TEST_CSV)
    ap.add_argument("--ckpt-dirs", nargs="+", default=DEFAULT_CKPT_DIRS,
                    help="run dirs under training/runs/ (best.pt is used)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    torch.set_num_threads(8)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    ckpts = [ROOT / "training" / "runs" / d / "best.pt" for d in args.ckpt_dirs]
    for ck in ckpts:
        if not ck.exists():
            raise FileNotFoundError(ck)

    df = pd.read_csv(args.test_csv)
    df["VH_c"] = df.VH.map(clean_ab)
    df["VL_c"] = df.VL.map(clean_ab)
    df["ag_c"] = df.antigen.map(clean_ag)
    for col in ("VH_c", "VL_c", "ag_c"):
        bad = df[~df[col].str.fullmatch(r"[ACDEFGHIKLMNPQRSTVWY]+")]
        assert bad.empty, f"alphabet violation in {col}: {bad.index.tolist()}"
    df["len_h"] = df.VH_c.str.len()  # chain boundary for chain_aware ckpts

    log.info("extracting AntiBERTy embeddings (%d rows)", len(df))
    ab_enc = AntiBERTyEncoder()
    df["h_ab"] = [extract_antibody(ab_enc, vh, vl, CACHE_DIR)
                  for vh, vl in zip(df.VH_c, df.VL_c)]

    uniq_ag = df.ag_c.unique()
    log.info("extracting ESM-2 embeddings (%d unique antigens)", len(uniq_ag))
    tok = AutoTokenizer.from_pretrained(ESM_DIR)
    esm = AutoModel.from_pretrained(ESM_DIR).eval()
    ag_map = {s: extract_antigen(tok, esm, s, CACHE_DIR) for s in uniq_ag}
    df["h_ag"] = df.ag_c.map(ag_map)

    # struct arm: detect from checkpoint configs before scoring
    cfgs = [torch.load(ck, map_location="cpu", weights_only=False)["config"]
            for ck in ckpts]
    need_s_ab = any(c["model"].get("struct_ab_dim", 0) > 0 for c in cfgs)
    need_s_ag = any(c["model"].get("struct_ag_dim", 0) > 0 for c in cfgs)
    if need_s_ab or need_s_ag:
        from extract_prostt5 import ProstT5Encoder
        log.info("struct checkpoints detected; extracting ProstT5 embeddings")
        s_enc = ProstT5Encoder(str(ROOT / "model_data" / "prostt5"))
        if need_s_ab:
            df["s_ab"] = [extract_struct_ab(s_enc, vh, vl, CACHE_DIR)
                          for vh, vl in zip(df.VH_c, df.VL_c)]
        if need_s_ag:
            s_ag_map = {s: extract_struct_ag(s_enc, s, CACHE_DIR)
                        for s in uniq_ag}
            df["s_ag"] = df.ag_c.map(s_ag_map)
        del s_enc
        if device.type == "cuda":
            torch.cuda.empty_cache()

    per_seed, names = [], []
    for ck in ckpts:
        c = torch.load(ck, map_location="cpu", weights_only=False)
        model = AffinityRanker(c["config"]["model"]).to(device)
        model.load_state_dict(c["model_state"])
        model.eval()
        scores = np.full(len(df), np.nan)
        for gid, sub in df.groupby("group"):
            sc = score_group(
                model, list(sub.h_ab), list(sub.h_ag), device,
                chain_lens=list(sub.len_h),
                s_abs=list(sub.s_ab) if "s_ab" in sub.columns else None,
                s_ags=list(sub.s_ag) if "s_ag" in sub.columns else None)
            scores[sub.index] = sc
        per_seed.append(scores)
        names.append(ck.parent.name)
        log.info("scored with %s (ep=%s, mon_sp=%.4f, chain_aware=%s, "
                 "struct_ab=%d, struct_ag=%d)",
                 ck.parent.name, c["epoch"], c["val_spearman"],
                 model.chain_aware, getattr(model, "struct_ab_dim", 0),
                 getattr(model, "struct_ag_dim", 0))

    S = np.stack(per_seed, axis=1)  # [n_rows, n_seeds]
    for j, name in enumerate(names):
        df[f"score_{name}"] = S[:, j]

    # Borda ensemble: mean of per-seed ranks within each group
    ranks = np.zeros_like(S)
    out_rank = np.zeros(len(df), dtype=int)
    for gid, sub in df.groupby("group"):
        idx = sub.index.to_numpy()
        for s in range(S.shape[1]):
            order = np.argsort(-S[idx, s])          # high score = better
            r = np.empty(len(idx))
            r[order] = np.arange(1, len(idx) + 1)   # rank 1 = best
            ranks[idx, s] = r
        mean_rank = ranks[idx].mean(axis=1)
        order = np.argsort(mean_rank)
        final = np.empty(len(idx), dtype=int)
        final[order] = np.arange(1, len(idx) + 1)
        out_rank[idx] = final
    for j, name in enumerate(names):
        df[f"rank_{name}"] = ranks[:, j].astype(int)
    df["pred_rank"] = out_rank

    args.out.parent.mkdir(parents=True, exist_ok=True)
    base_cols = (["seq_id"] if "seq_id" in df.columns else []) + \
        ["group", "VH", "VL", "pred_rank"]
    out = df.reset_index().rename(columns={"index": "row_idx"})[
        ["row_idx"] + base_cols +
        [f"{k}_{name}" for k in ("rank", "score") for name in names]].copy()
    out = out.sort_values(["group", "pred_rank"]).reset_index(drop=True)
    out.to_csv(args.out, index=False)
    for gid, sub in out.groupby("group"):
        n = len(sub)
        assert sorted(sub.pred_rank) == list(range(1, n + 1)), gid
    log.info("wrote %s", args.out)
    print(json.dumps({"rows": len(out), "seeds": names,
                      "groups": {str(g): sorted(map(int, s.pred_rank)) ==
                                 list(range(1, len(s) + 1))
                                 for g, s in out.groupby("group")}}, indent=1))


if __name__ == "__main__":
    main()
